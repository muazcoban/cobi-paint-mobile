#!/usr/bin/env python3
"""Sticker pictures for the sticker tool.

The catalog below -> download the Fluent UI Emoji "Flat" SVGs (same source,
pinned commit and MIT license as the coloring pages) -> render 256 px PNGs
with ImageMagick -> assets/stickers/<code>.png + lib/data/stickers.dart.

    python3 tool/stickers/build_stickers.py --work /tmp/cobi-stickers

The order of the catalog is the order the stickers are stamped in, so it
alternates subjects: a trail of stickers looks varied.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PAGE_CATALOG = os.path.join(ROOT, "tool", "pages", "catalog.json")
ASSETS = os.path.join(ROOT, "assets", "stickers")
DART_FILE = os.path.join(ROOT, "lib", "data", "stickers.dart")
SIZE = 256

# code, Fluent name, Turkish name, English name
CATALOG = [
    ("star", "Star", "yıldız", "star"),
    ("red_heart", "Red heart", "kalp", "heart"),
    ("sunflower", "Sunflower", "ayçiçeği", "sunflower"),
    ("butterfly", "Butterfly", "kelebek", "butterfly"),
    ("sun", "Sun", "güneş", "sun"),
    ("lady_beetle", "Lady beetle", "uğur böceği", "ladybug"),
    ("balloon", "Balloon", "balon", "balloon"),
    ("rainbow", "Rainbow", "gökkuşağı", "rainbow"),
    ("strawberry", "Strawberry", "çilek", "strawberry"),
    ("grinning_face", "Grinning face", "gülen yüz", "smiley"),
    ("cloud", "Cloud", "bulut", "cloud"),
    ("crown", "Crown", "taç", "crown"),
    ("red_apple", "Red apple", "elma", "apple"),
    ("musical_note", "Musical note", "nota", "music note"),
    ("crescent_moon", "Crescent moon", "ay", "moon"),
    ("sparkles", "Sparkles", "pırıltı", "sparkles"),
]


def fluent_url(source, name):
    folder = name.replace(" ", "%20")
    file = re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")
    return f"https://raw.githubusercontent.com/{source['repo']}/{source['commit']}/assets/{folder}/Flat/{file}_flat.svg"


def fetch(url, path):
    if os.path.exists(path) and os.path.getsize(path) > 0:
        return True
    try:
        data = urllib.request.urlopen(url, timeout=30).read()
    except Exception as e:
        print(f"  download failed: {url}: {e}", file=sys.stderr)
        return False
    if not data:
        return False
    with open(path, "wb") as f:
        f.write(data)
    return True


def render(svg, png):
    # 32 px art at 1536 dpi is 512 px; the resize down gives clean edges.
    subprocess.run(
        ["magick", "-background", "none", "-density", "1536", svg, "-resize", f"{SIZE}x{SIZE}",
         "-gravity", "center", "-extent", f"{SIZE}x{SIZE}", png],
        check=True,
    )


def write_dart(source):
    lines = [
        "// GENERATED by tool/stickers/build_stickers.py; do not edit by hand.",
        f"// Source art: {source['name']} ({source['license']}), {source['repo']} @ {source['commit'][:12]}.",
        "",
        "/// One sticker picture under assets/stickers, with the names VoiceOver",
        "/// speaks; the child never reads them.",
        "class StickerInfo {",
        "  const StickerInfo({required this.code, required this.nameTr, required this.nameEn});",
        "",
        "  final String code;",
        "  final String nameTr;",
        "  final String nameEn;",
        "",
        "  String get assetPath => 'assets/stickers/$code.png';",
        "",
        "  String localizedName(String languageCode) => languageCode == 'tr' ? nameTr : nameEn;",
        "}",
        "",
        "/// The stickers in the order they are stamped.",
        "const stickers = <StickerInfo>[",
    ]
    for code, _, tr, en in CATALOG:
        lines.append(f"  StickerInfo(code: '{code}', nameTr: '{tr}', nameEn: '{en}'),")
    lines += ["];", ""]
    with open(DART_FILE, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--work", required=True, help="folder for the downloaded SVGs")
    ap.add_argument("--force", action="store_true", help="render again even if the PNG exists")
    args = ap.parse_args()
    with open(PAGE_CATALOG, encoding="utf-8") as f:
        source = json.load(f)["source"]
    os.makedirs(args.work, exist_ok=True)
    os.makedirs(ASSETS, exist_ok=True)
    failed = []
    for code, name, _, _ in CATALOG:
        svg = os.path.join(args.work, f"{code}.svg")
        png = os.path.join(ASSETS, f"{code}.png")
        if not fetch(fluent_url(source, name), svg):
            failed.append(code)
            continue
        if args.force or not os.path.exists(png):
            render(svg, png)
            print(f"  {code}: rendered")
    write_dart(source)
    if failed:
        print("FAILED: " + ", ".join(failed), file=sys.stderr)
        sys.exit(1)
    print(f"{len(CATALOG)} stickers in {ASSETS}, list in {DART_FILE}")


if __name__ == "__main__":
    main()
